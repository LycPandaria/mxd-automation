"""几何计算工具。

================================================================================
用途
================================================================================

  供决策层判断怪物是否在攻击范围内、计算移动距离等。
  所有函数都是纯函数（无副作用），接收坐标返回计算结果。

================================================================================
坐标系
================================================================================

  项目中所有坐标都是 (x, y) 格式，x 向右增大，y 向下增大。
  原点 (0, 0) 在窗口客户区左上角。

================================================================================
距离类型
================================================================================

  欧氏距离 (distance): 直线距离，sqrt(dx² + dy²)
    用于判断"怪物是否在攻击范围内"

  曼哈顿距离 (manhattan): 网格距离，|dx| + |dy|
    用于 A* 寻路的启发式估计（只允许上下左右移动时）
"""
import math
from typing import Tuple


def distance(p1: Tuple[float, float], p2: Tuple[float, float]) -> float:
    """计算两点之间的欧氏距离（直线距离）。

    公式: sqrt((x2-x1)² + (y2-y1)²)

    Args:
        p1: 点1坐标 (x, y)
        p2: 点2坐标 (x, y)

    Returns:
        两点之间的欧氏距离

    Example:
        >>> distance((0, 0), (3, 4))
        5.0
    """
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])


def in_range(point: Tuple[float, float],
             center: Tuple[float, float],
             radius: float) -> bool:
    """判断 point 是否在以 center 为圆心、radius 为半径的圆内。

    常用于判断怪物是否在攻击范围内。

    Args:
        point:  待判断的点坐标 (x, y)
        center: 圆心坐标 (x, y)
        radius: 圆半径

    Returns:
        True 表示点在圆内（含边界），False 表示在圆外

    Example:
        >>> in_range((5, 5), (0, 0), 10)
        True
        >>> in_range((15, 15), (0, 0), 10)
        False
    """
    return distance(point, center) <= radius


def manhattan(p1: Tuple[float, float], p2: Tuple[float, float]) -> float:
    """计算两点之间的曼哈顿距离（网格距离）。

    公式: |x2-x1| + |y2-y1|

    曼哈顿距离是 A* 寻路中常用的启发式函数，
    前提是只允许上下左右四个方向移动。

    Args:
        p1: 点1坐标 (x, y)
        p2: 点2坐标 (x, y)

    Returns:
        两点之间的曼哈顿距离

    Example:
        >>> manhattan((0, 0), (3, 4))
        7
    """
    return abs(p1[0] - p2[0]) + abs(p1[1] - p2[1])